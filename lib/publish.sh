# shellcheck shell=bash
# driftless publish OUT [--push [--tag vX.Y.Z]]: the public template, from this repository.
#
# Personal things live in their own places, so publishing is leaving them out, not rewriting files:
# personal/ (your layer: manifest, config, notes, calendar), hosts/* except hosts/example, signers/.
# As a last guard every published file is searched for the terms in personal/forbidden (one extended
# regex per line); a hit aborts before anything is written to OUT's history.
#
# The public history is signed like the private one: the commit and the release tag carry this
# machine's SSH signature, and docs/release-signers lists the public keys of signers/ (without their
# host names) in git's allowed signers format, so anyone can check a release with git verify-tag.

PUBLIC_EXCLUDE=(':!personal' ':!signers' ':!hosts')
RELEASE_SIGNERS=docs/release-signers

# release_signers: the allowed signers file for the public template, from the committed signers/
release_signers() {
  local f
  echo "# The keys that sign the releases of this template (SSH, git's allowed signers format)."
  echo "# Check a release: git -c gpg.ssh.allowedSignersFile=$RELEASE_SIGNERS verify-tag vX.Y.Z"
  echo "# Generated by driftless publish from signers/; do not edit."
  for f in $(git -C "$DRIFTLESS" ls-files -- 'signers/*.pub'); do
    git -C "$DRIFTLESS" show "HEAD:$f" | awk '{ print "driftless-release namespaces=\"git\"", $1, $2 }'
  done
}

cmd_publish() {
  local out='' push='' tag='' files hits msg
  while (($#)); do
    case $1 in
      --push) push=1 ;;
      --tag) tag=${2:?--tag needs a name, e.g. v2.31.0} && shift ;;
      -*) die "unknown option $1; usage: driftless publish OUT [--push [--tag vX.Y.Z]]" ;;
      *) out=$1 ;;
    esac
    shift
  done
  [[ -n $out ]] || die "usage: driftless publish OUT [--push [--tag vX.Y.Z]]"
  [[ -d $out/.git ]] || die "$out is not a git clone of the public repository"
  [[ -z $tag || -n $push ]] || die "--tag needs --push: a tag goes with what is published"
  [[ -z $(git -C "$DRIFTLESS" status --porcelain) ]] || die "commit first: the export takes the committed state"
  if [[ -n $push ]]; then
    [[ -f $SIGNING_KEY.pub ]] || die "no signing key ($SIGNING_KEY): run driftless signing setup"
    [[ -z $tag ]] || ! git -C "$out" rev-parse -q --verify "refs/tags/$tag" > /dev/null ||
      die "$out already has a tag $tag"
  fi
  mapfile -t files < <(
    git -C "$DRIFTLESS" ls-files -- . "${PUBLIC_EXCLUDE[@]}"
    git -C "$DRIFTLESS" ls-files -- hosts/example
  )
  # the published tree is exactly the listed files: remove everything else first (not .git)
  find "$out" -mindepth 1 -maxdepth 1 ! -name .git -exec rm -rf {} +
  (cd "$DRIFTLESS" && printf '%s\0' "${files[@]}" | xargs -0 cp --parents -a -t "$out")
  if [[ -n $(git -C "$DRIFTLESS" ls-files -- 'signers/*.pub') ]]; then
    mkdir -p "$out/${RELEASE_SIGNERS%/*}"
    release_signers > "$out/$RELEASE_SIGNERS"
  fi
  if grep -qv '^\s*\(#\|$\)' "$DRIFTLESS/personal/forbidden" 2> /dev/null; then
    hits=$(grep -rnIE -f <(grep -v '^\s*\(#\|$\)' "$DRIFTLESS/personal/forbidden") "$out" --exclude-dir=.git | head -20 || true)
    [[ -z $hits ]] || die "personal terms in the export, nothing committed:
$hits"
  else
    warn "personal/forbidden has no terms: the export was not checked for personal words"
  fi
  git -C "$out" add -A
  msg="Update from $(git -C "$DRIFTLESS" rev-parse --short HEAD)"
  if git -C "$out" diff --cached --quiet; then
    echo "public template already up to date"
    [[ -n $tag ]] || return 0
  else
    git -C "$out" diff --cached --stat | tail -1
    [[ -n $push ]] || {
      echo "staged in $out; commit and push with: driftless publish $out --push [--tag vX.Y.Z]"
      return 0
    }
    sign_in "$out" commit -q -S -m "$msg"
  fi
  [[ -z $tag ]] || sign_in "$out" tag -s -m "driftless $tag" "$tag"
  git -C "$out" push -q
  [[ -z $tag ]] || git -C "$out" push -q origin "refs/tags/$tag"
  echo "published: $msg${tag:+, signed tag $tag}"
}

# sign_in DIR GIT-ARGS...: git in DIR, signing with this machine's key whatever DIR's config says
sign_in() {
  local dir=$1
  shift
  git -C "$dir" -c gpg.format=ssh -c user.signingkey="$SIGNING_KEY.pub" "$@"
}
